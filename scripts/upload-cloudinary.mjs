/* global FormData, Blob, fetch, AbortSignal, console */
import process from 'node:process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { wallpaperTemplates } from '../src/assets/templates.js';
import manifest from '../src/assets/cloudinaryManifest.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Local overrides take precedence. Never print credentials or upload responses.
for (const file of ['.env.local', '.env']) {
  if (existsSync(resolve(root, file))) process.loadEnvFile(resolve(root, file));
}
const names = ['CLOUDINARY_CLOUD_NAME', 'CLOUDINARY_API_KEY', 'CLOUDINARY_API_SECRET'];
if (names.some((name) => !process.env[name]?.trim())) {
  throw new Error('Fill all three CLOUDINARY_ variables in .env.local before uploading.');
}
const cloud = process.env.CLOUDINARY_CLOUD_NAME.trim();
if (!/^[a-z0-9_-]+$/i.test(cloud)) throw new Error('Invalid Cloudinary cloud name.');
const paths = [...new Set(wallpaperTemplates.flatMap((template) =>
  [template.image, ...Object.values(template.deviceImages || {})].filter(Boolean)))].sort();
const dryRun = process.argv.includes('--dry-run');
let uploaded = 0;
let manifestWrites = Promise.resolve();
async function uploadPath(path) {
  if (!path.startsWith('/wallpapers/') || path.includes('..')) throw new Error('Unexpected artwork path.');
  const bytes = await readFile(resolve(root, 'public', path.slice(1)));
  const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const publicId = `schedsnap${path.replace(/\.\w+$/, '')}-${digest}`;
  if (manifest[path]?.publicId === publicId && manifest[path]?.cloud === cloud) return;
  if (dryRun) { uploaded++; return; }
  const timestamp = String(Math.floor(Date.now() / 1000));
  const parameters = { overwrite: 'false', public_id: publicId, timestamp };
  const signature = createHash('sha1').update(Object.entries(parameters)
    .sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => `${key}=${value}`).join('&')
    + process.env.CLOUDINARY_API_SECRET.trim()).digest('hex');
  const body = new FormData();
  for (const [key, value] of Object.entries(parameters)) body.set(key, value);
  body.set('api_key', process.env.CLOUDINARY_API_KEY.trim());
  body.set('signature', signature);
  body.set('file', new Blob([bytes]), path.split('/').at(-1));
  const response = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/image/upload`, {
    method: 'POST', body, signal: AbortSignal.timeout(120_000),
  });
  if (!response.ok) {
    const failure = await response.json().catch(() => ({}));
    const message = failure.error?.message || '';
    const reason = /invalid api_key/i.test(message) ? 'API key rejected'
      : /signature/i.test(message) ? 'Upload signature rejected; check the API secret'
        : /cloud name/i.test(message) ? 'Cloud name rejected' : 'Check credentials and account limits';
    throw new Error(`Cloudinary upload failed (${response.status}) for ${path}: ${reason}. Rerun to resume.`);
  }
  const asset = await response.json();
  if (!asset.secure_url || !asset.width || !asset.height) throw new Error(`Incomplete upload metadata for ${path}.`);
  manifest[path] = { cloud, publicId, url: asset.secure_url, width: asset.width, height: asset.height };
  manifestWrites = manifestWrites.then(() => writeFile(resolve(root, 'src/assets/cloudinaryManifest.js'),
    '// Generated by scripts/upload-cloudinary.mjs. Contains public asset metadata only.\nexport default '
      + JSON.stringify(manifest, null, 2) + ';\n'));
  await manifestWrites;
  uploaded++;
  console.log(`Uploaded ${uploaded}: ${path}`);
}
// Independent uploads run in a small pool; manifest writes remain serialized.
let nextPath = 0;
const results = await Promise.allSettled(Array.from({ length: dryRun ? 1 : 4 }, async () => {
  while (nextPath < paths.length) await uploadPath(paths[nextPath++]);
}));
const failure = results.find((result) => result.status === 'rejected');
if (failure) throw failure.reason;
console.log(dryRun ? `Credentials present. ${uploaded} artworks pending upload (${paths.length} referenced total).`
  : `Complete: ${uploaded} uploaded; ${paths.length} referenced artworks mapped.`);
