/* global FormData, Blob, fetch, AbortSignal, console */
import process from 'node:process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile, writeFile, rename, unlink } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { wallpaperTemplates } from '../src/assets/templates.js';
import manifest from '../src/assets/cloudinaryManifest.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Local overrides take precedence. Never print credentials or upload responses.
for (const file of ['.env.local', '.env']) {
  if (existsSync(resolve(root, file))) process.loadEnvFile(resolve(root, file));
}
const names = ['CLOUDINARY_CLOUD_NAME', 'CLOUDINARY_API_KEY', 'CLOUDINARY_API_SECRET'];
if (names.some((name) => !process.env[name]?.trim())) {
  throw new Error('Fill all three CLOUDINARY_ variables in .env.local before uploading.');
}
const cloud = process.env.CLOUDINARY_CLOUD_NAME.trim();
if (!/^[a-z0-9_-]+$/i.test(cloud)) throw new Error('Invalid Cloudinary cloud name.');
const packNames = ['mascots', 'pixel-mascots', 'goofy-mascots', 'doodle-mascots'];
const uploadPacks = process.argv.includes('--mascot-packs');
const checkpoint = resolve(root, 'output/cloudinary-upload-mascots.json');
if (uploadPacks && existsSync(checkpoint)) Object.assign(manifest, JSON.parse(await readFile(checkpoint, 'utf8')));
const pendingManifest = resolve(root, 'src/assets/cloudinaryManifest.js.upload-tmp');
if (existsSync(pendingManifest)) {
  const pending = await readFile(pendingManifest, 'utf8');
  Object.assign(manifest, JSON.parse(pending.slice(pending.indexOf('export default ') + 15).trim().replace(/;$/, '')));
}
const packManifests = uploadPacks ? await Promise.all(packNames.map(async name => ({ name,
  data: JSON.parse(await readFile(resolve(root, 'public/images', name, 'manifest.json'), 'utf8')),
}))) : [];
const artworkManifestIndex = process.argv.indexOf('--artwork-manifest');
let scopedPaths;
if (artworkManifestIndex !== -1) {
  if (uploadPacks) throw new Error('Use either --artwork-manifest or --mascot-packs.');
  const manifestFile = process.argv[artworkManifestIndex + 1];
  if (!manifestFile || manifestFile.startsWith('--')) throw new Error('Pass a verified artwork manifest after --artwork-manifest.');
  const artwork = JSON.parse(await readFile(resolve(root, manifestFile), 'utf8'));
  if (!Array.isArray(artwork.assets) || !artwork.assets.length) throw new Error('Artwork manifest must contain assets.');
  scopedPaths = [];
  for (const asset of artwork.assets) {
    if (!/^public\/wallpapers\/scenic\/[a-z0-9-]+\/(mobile|tablet|laptop)\.png$/.test(asset.path)
      || !asset.dimensionsValid || !asset.opaque || !/^[a-f0-9]{64}$/.test(asset.sha256)) {
      throw new Error('Artwork manifest contains an unverified or unexpected background.');
    }
    const bytes = await readFile(resolve(root, asset.path));
    const expected = { mobile: [1080, 2400], tablet: [1600, 2560], laptop: [1920, 1080] }[asset.path.split('/').at(-1).slice(0, -4)];
    if (createHash('sha256').update(bytes).digest('hex') !== asset.sha256
      || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a'
      || bytes.readUInt32BE(16) !== expected[0] || bytes.readUInt32BE(20) !== expected[1]) {
      throw new Error(`Artwork changed or has invalid dimensions: ${asset.path}`);
    }
    scopedPaths.push('/' + asset.path.slice('public/'.length));
  }
  if (new Set(scopedPaths).size !== scopedPaths.length) throw new Error('Artwork manifest contains duplicate paths.');
}
const paths = [...new Set(scopedPaths || (uploadPacks ? packManifests.flatMap(({ data }) => data.assets.map(asset => asset.master))
  : wallpaperTemplates.flatMap((template) => [template.image, ...Object.values(template.deviceImages || {})].filter(Boolean))))].sort();
const dryRun = process.argv.includes('--dry-run');
let uploaded = 0;
let manifestWrites = Promise.resolve();
async function saveManifest() {
  const destination = resolve(root, 'src/assets/cloudinaryManifest.js');
  const temporary = destination + '.upload-tmp';
  const content = '// Generated by scripts/upload-cloudinary.mjs. Contains public asset metadata only.\nexport default '
    + JSON.stringify(manifest, null, 2) + ';\n';
  for (let attempt = 0; attempt < 5; attempt++) {
    try { await writeFile(temporary, content); await rename(temporary, destination); return; }
    catch {
      if (attempt === 4) { await writeFile(destination, content); await unlink(temporary).catch(() => {}); return; }
      await delay(200 * (attempt + 1));
    }
  }
}
async function uploadPath(path) {
  if ((!path.startsWith('/wallpapers/') && !/^\/images\/(mascots|pixel-mascots|goofy-mascots|doodle-mascots)\/(masters|mobile|tablet|laptop)\/[a-z0-9-]+\.(png|webp)$/.test(path)) || path.includes('..')) throw new Error('Unexpected artwork path.');
  const bytes = await readFile(resolve(root, 'public', path.slice(1)));
  const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const publicId = `schedsnap${path.replace(/\.\w+$/, '')}-${digest}`;
  if (manifest[path]?.publicId === publicId && manifest[path]?.cloud === cloud) return;
  if (dryRun) { uploaded++; return; }
  const timestamp = String(Math.floor(Date.now() / 1000));
  const parameters = { overwrite: 'false', public_id: publicId, timestamp };
  const signature = createHash('sha1').update(Object.entries(parameters)
    .sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => `${key}=${value}`).join('&')
    + process.env.CLOUDINARY_API_SECRET.trim()).digest('hex');
  const body = new FormData();
  for (const [key, value] of Object.entries(parameters)) body.set(key, value);
  body.set('api_key', process.env.CLOUDINARY_API_KEY.trim());
  body.set('signature', signature);
  body.set('file', new Blob([bytes]), path.split('/').at(-1));
  const response = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/image/upload`, {
    method: 'POST', body, signal: AbortSignal.timeout(120_000),
  });
  if (!response.ok) {
    const failure = await response.json().catch(() => ({}));
    const message = failure.error?.message || '';
    const reason = /invalid api_key/i.test(message) ? 'API key rejected'
      : /signature/i.test(message) ? 'Upload signature rejected; check the API secret'
        : /cloud name/i.test(message) ? 'Cloud name rejected' : 'Check credentials and account limits';
    throw new Error(`Cloudinary upload failed (${response.status}) for ${path}: ${reason}. Rerun to resume.`);
  }
  const asset = await response.json();
  if (!asset.secure_url || !asset.width || !asset.height) throw new Error(`Incomplete upload metadata for ${path}.`);
  manifest[path] = { cloud, publicId, url: asset.secure_url, width: asset.width, height: asset.height };
  // Keep resumable progress outside source files while uploads are in flight.
  manifestWrites = manifestWrites.then(() => uploadPacks
    ? writeFile(checkpoint, JSON.stringify(manifest, null, 2) + '\n') : saveManifest());
  await manifestWrites;
  uploaded++;
  console.log(`Uploaded ${uploaded}: ${path}`);
}
// Independent uploads run in a small pool; manifest writes remain serialized.
let nextPath = 0;
const results = await Promise.allSettled(Array.from({ length: dryRun ? 1 : 4 }, async () => {
  while (nextPath < paths.length) await uploadPath(paths[nextPath++]);
}));
const failure = results.find((result) => result.status === 'rejected');
if (failure) throw failure.reason;
if (uploadPacks && !dryRun) await saveManifest();
if (uploadPacks && !dryRun) {
  for (const { name, data } of packManifests) {
    data.cloudinaryStatus = 'uploaded';
    await writeFile(resolve(root, 'public/images', name, 'manifest.json'), JSON.stringify(data, null, 2) + '\n');
  }
}
console.log(dryRun ? `Credentials present. ${uploaded} artworks pending upload (${paths.length} referenced total).`
  : `Complete: ${uploaded} uploaded; ${paths.length} referenced artworks mapped.`);
