/* global console */
import process from 'node:process';
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import manifest from '../src/assets/cloudinaryManifest.js';
import { scenicTemplates } from '../src/assets/scenicTemplates.js';
import { mascotTemplates } from '../src/assets/mascotTemplates.js';
import { generatedMascotTemplates } from '../src/assets/generatedMascotTemplates.js';
import { wallpaperTemplates } from '../src/assets/templates.js';
import { createCatalogStore } from '../server/catalogStore.js';
import { artworkIds, createArtworkDeleter } from '../server/deleteArtwork.js';
for (const file of ['.env.local', '.env']) if (existsSync(file)) process.loadEnvFile(file);
const store = createCatalogStore(process.env);
const before = await store.read(true);
const retired = [...scenicTemplates, ...mascotTemplates, ...generatedMascotTemplates];
const retiredIds = new Set(retired.map(t => t.id));
const remove = t => retiredIds.has(t.id) || ['scenic', 'mascot'].includes(t.collection);
const removed = before.templates.filter(remove);
const kept = before.templates.filter(t => !remove(t)).map(t => ['chikawa', 'little-friends'].includes(t.collection) ? { ...t, collection: 'chiikawa' } : t);
const protectedAssets = new Set([...kept, ...wallpaperTemplates].flatMap(t => artworkIds(t, process.env)));
const candidates = new Set([...retired, ...removed].flatMap(t => artworkIds(t, process.env)));
const deletionIds = [...candidates].filter(id => !id.startsWith('local:') && !protectedAssets.has(id));
await writeFile('output/retired-collections-review.json', JSON.stringify({ before, proposed: { ...before, templates: kept }, deletionIds }, null, 2));
console.log(JSON.stringify({ removedDesigns: removed.length, keptDesigns: kept.length, chiikawa: kept.filter(t => t.collection === 'chiikawa').length, deleteAssets: deletionIds.length }));
if (process.argv.includes('--apply')) {
  if (JSON.stringify(await store.read(true)) !== JSON.stringify(before)) throw Error('Catalog changed during review.');
  await store.write({ ...before, templates: kept });
  const saved = await store.read(true);
  if (JSON.stringify(saved.templates) !== JSON.stringify(kept)) throw Error('Catalog verification failed.');
  const destroy = createArtworkDeleter(process.env);
  let cursor = 0;
  const completed = [];
  const results = await Promise.allSettled(Array.from({ length: 4 }, async () => {
    while (cursor < deletionIds.length) {
      const id = deletionIds[cursor++];
      await destroy(id);
      completed.push(id);
      if (completed.length % 40 === 0) console.log(`Deleted ${completed.length}/${deletionIds.length} assets`);
    }
  }));
  for (const [path, asset] of Object.entries(manifest)) if (completed.includes(asset.publicId)) delete manifest[path];
  await writeFile('src/assets/cloudinaryManifest.js', '// Generated by scripts/upload-cloudinary.mjs. Contains public asset metadata only.\nexport default ' + JSON.stringify(manifest, null, 2) + ';\n');
  await writeFile('output/retired-collections-result.json', JSON.stringify({ revision: saved.revision, removedDesigns: removed.length, keptDesigns: kept.length, deletedAssets: completed, failures: results.filter(r => r.status === 'rejected').map(r => String(r.reason)) }, null, 2));
  for (const result of results) if (result.status === 'rejected') throw result.reason;
  console.log('Catalog and asset deletion verified.');
}
