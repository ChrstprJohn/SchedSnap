/* global console, fetch, FormData, AbortSignal */
import process from 'node:process';
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import manifest from '../src/assets/cloudinaryManifest.js';
import { signCloud } from '../server/catalogStore.js';

const root = process.cwd();
for (const file of ['.env.local', '.env']) if (existsSync(resolve(root, file))) process.loadEnvFile(resolve(root, file));
const paths = Object.keys(manifest).filter(path => /^\/images\/(mascots|pixel-mascots|goofy-mascots|doodle-mascots)\/(mobile|tablet|laptop)\/[a-z0-9-]+\.(png|webp)$/.test(path));
const protectedIds = new Set(Object.entries(manifest).filter(([path]) => !paths.includes(path)).map(([, asset]) => asset.publicId));
for (const path of paths) {
  if (!manifest[path].publicId.startsWith(`schedsnap${path.replace(/\.\w+$/, '')}-`) || protectedIds.has(manifest[path].publicId)) throw new Error(`Refusing unexpected asset ID for ${path}.`);
}
let cursor = 0, removed = 0;
const results = await Promise.allSettled(Array.from({ length: 4 }, async () => {
  while (cursor < paths.length) {
    const path = paths[cursor++];
    const parameters = { public_id: manifest[path].publicId, invalidate: 'true', timestamp: String(Math.floor(Date.now() / 1000)) };
    const body = new FormData();
    for (const [key, value] of Object.entries(parameters)) body.set(key, value);
    body.set('api_key', process.env.CLOUDINARY_API_KEY);
    body.set('signature', signCloud(parameters, process.env));
    const response = await fetch(`https://api.cloudinary.com/v1_1/${process.env.CLOUDINARY_CLOUD_NAME}/image/destroy`, { method: 'POST', body, signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Cloudinary removal failed (${response.status}) for ${path}.`);
    const result = await response.json();
    if (!['ok', 'not found'].includes(result.result)) throw new Error(`Removal not confirmed for ${path}.`);
    delete manifest[path]; removed++;
    if (removed % 50 === 0) console.log(`Removed ${removed}/${paths.length} padded layout uploads.`);
  }
}));
await writeFile(resolve(root, 'src/assets/cloudinaryManifest.js'), '// Generated by scripts/upload-cloudinary.mjs. Contains public asset metadata only.\nexport default ' + JSON.stringify(manifest, null, 2) + ';\n');
await writeFile(resolve(root, 'output/cloudinary-upload-mascots.json'), JSON.stringify(manifest, null, 2) + '\n');
const failure = results.find(result => result.status === 'rejected');
if (failure) throw failure.reason;
console.log(`Removed all ${removed} padded layout uploads; mascot masters preserved.`);
