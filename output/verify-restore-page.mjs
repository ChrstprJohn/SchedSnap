import { chromium } from 'file:///C:/Users/picar/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { sampleSchedule } from '../src/assets/sampleSchedule.js';
import { draftKey } from '../src/lib/scheduleDraft.js';
const base = 'https://schedsnap.chrbuilds.dev';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  const page = await browser.newPage();
  await page.goto(base);
  await page.evaluate(({ key, schedule }) => sessionStorage.setItem(key, JSON.stringify({ schedule, title: 'Saved timetable' })), { key: draftKey, schedule: sampleSchedule });
  await page.goto(`${base}/services/schedule-wallpaper?collection=onepiece`);
  await page.getByRole('heading', { name: 'Choose a design', exact: true }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Restore your classes?', exact: true }).count(), 0);
  assert.ok(await page.evaluate(key => sessionStorage.getItem(key), draftKey));
  const cookies = page.getByRole('button', { name: 'Reject cookies', exact: true });
  if (await cookies.count()) await cookies.click();
  await page.getByRole('button', { name: 'Preview Cumulus Meadow, New design', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Restore your classes?', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Use this design', exact: true }).click();
  await page.getByRole('heading', { name: 'Add your classes', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Restore your classes?', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Restore classes', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Restore your classes?', exact: true }).count(), 0);
  await page.getByText('Saved timetable', { exact: true }).waitFor();
  await page.close();
  const preview = await browser.newPage();
  await preview.goto(base);
  await preview.evaluate(({ key, schedule }) => sessionStorage.setItem(key, JSON.stringify({ schedule, title: 'Saved timetable' })), { key: draftKey, schedule: sampleSchedule });
  await preview.goto(`${base}/services/schedule-wallpaper/onepiece-cumulus-meadow?step=preview`);
  await preview.getByRole('heading', { name: 'Your wallpaper', exact: true }).waitFor();
  assert.equal(await preview.getByRole('heading', { name: 'Restore your classes?', exact: true }).count(), 0);
  await preview.getByRole('button', { name: 'Back', exact: true }).click();
  await preview.getByRole('heading', { name: 'Restore your classes?', exact: true }).waitFor();
  await preview.getByRole('button', { name: 'Discard draft', exact: true }).click();
  assert.equal(await preview.evaluate(key => sessionStorage.getItem(key), draftKey), null);
  await writeFile('documentation/RESTORE_CLASSES_PAGE_VALIDATION.json', JSON.stringify({ checkedAt: new Date().toISOString(), website: base, chooseDesignNoDialog: true, designPreviewNoDialog: true, classesDialog: true, restoredTitle: true, wallpaperPreviewNoDialog: true, returningToClassesDialog: true, discardWorks: true }, null, 2) + '\n');
  console.log('Live restore flow verified: classes only; choose/preview stay clear; restore/discard work.');
} finally { await browser.close(); }
